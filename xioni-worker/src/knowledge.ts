// Πίνακας εκτίμησης κιλών (ΔΟΚΙΜΑΣΤΙΚΟΣ). Κιλά ανά μονάδα και ανά 24 ώρες.
const PER_DAY: Record<string, { kgPerUnitPerDay: number; unit: string; note: string }> = {
  shipping_frozen: { kgPerUnitPerDay: 5, unit: "ισοθερμικό κουτί (~30 λίτρα)", note: "για κατεψυγμένα προϊόντα" },
  shipping_chilled: { kgPerUnitPerDay: 2.5, unit: "ισοθερμικό κουτί (~30 λίτρα)", note: "για ψυχόμενα προϊόντα" },
  event_low_fog: { kgPerUnitPerDay: 10, unit: "εμφάνιση low fog (~3–4 λεπτά)", note: "με μηχανή low fog" },
  cocktails: { kgPerUnitPerDay: 0.1, unit: "ποτό", note: "για εφέ σε κοκτέιλ" },
  blasting: { kgPerUnitPerDay: 40, unit: "ώρα καθαρισμού", note: "για dry ice blasting" },
};

export function estimateKg(input: { use: string; units: number; hours: number }) {
  const row = PER_DAY[input.use];
  if (!row) return { error: `Άγνωστη χρήση: ${input.use}` };
  const days = input.use.startsWith("shipping") ? Math.max(input.hours, 1) / 24 : 1;
  const kg = Math.ceil(row.kgPerUnitPerDay * input.units * days * 1.15); // +15% περιθώριο εξάχνωσης
  return { kg, basis: `${row.kgPerUnitPerDay} κιλά ανά ${row.unit} ${row.note}, +15% περιθώριο`, demo: DEMO };
}

export const ESTIMATE_USES = Object.keys(PER_DAY);
